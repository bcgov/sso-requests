import React from 'react';
import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import ChatWidget from '@app/components/ChatWidget';

jest.mock('@app/services/auth', () => ({ getAuthHeader: jest.fn(async () => 'Bearer test-token') }));

const API = 'http://localhost:3000/api';

const sse = (delta: object, finishReason: string | null = null) =>
  `data: ${JSON.stringify({
    id: 'c1',
    object: 'chat.completion.chunk',
    created: 0,
    model: 'm',
    choices: [{ index: 0, delta, finish_reason: finishReason }],
  })}\n\n`;

const streamBody = (chunks: string[]) => {
  const encoder = new TextEncoder();
  let i = 0;
  return {
    getReader: () => ({
      read: async () => (i < chunks.length ? { done: false, value: encoder.encode(chunks[i++]) } : { done: true }),
      cancel: async () => undefined,
    }),
  };
};

const response = ({
  status = 200,
  json,
  body,
  headers = {},
}: {
  status?: number;
  json?: unknown;
  body?: ReturnType<typeof streamBody>;
  headers?: Record<string, string>;
}) => ({
  ok: status >= 200 && status < 300,
  status,
  headers: { get: (name: string) => headers[name] ?? null },
  json: async () => json,
  body,
});

const ANSWER_CHUNKS = [
  sse({ role: 'assistant' }),
  ': keepalive\n\n',
  sse({ status: 'searching' }),
  // Split mid-line to exercise the buffer.
  sse({ content: 'Use the **standard** realm.' }).slice(0, 40),
  sse({ content: 'Use the **standard** realm.' }).slice(40),
  sse({ grounding_status: 'PARTIALLY_SUPPORTED' }),
  sse({ citations: [{ title: 'Getting started', location: { uri: 'https://docs.example/start' } }] }),
  sse({}, 'stop'),
  'data: [DONE]\n\n',
];

type Route = (init?: RequestInit) => ReturnType<typeof response>;

const mockFetch = (routes: Record<string, Route>) => {
  const fetchMock = jest.fn(async (url: string, init?: RequestInit) => {
    const key = `${init?.method ?? 'GET'} ${url}`;
    const route = routes[key];
    if (!route) throw new Error(`unexpected fetch ${key}`);
    return route(init);
  });
  (global as any).fetch = fetchMock;
  return fetchMock;
};

const enabledStatus = () => response({ json: { enabled: true, maxPromptLength: 500 } });

const openWidget = async () => {
  fireEvent.click(await screen.findByTestId('chat-launcher'));
  return screen.findByTestId('chat-window');
};

// Opens the header menu and returns one of its options.
const menuOption = async (name: string | RegExp) => {
  if (screen.getByTestId('chat-menu').getAttribute('aria-expanded') !== 'true') {
    fireEvent.click(screen.getByTestId('chat-menu'));
  }
  return screen.findByRole('button', { name });
};

const ask = (text: string) => {
  fireEvent.change(screen.getByTestId('chat-input'), { target: { value: text } });
  fireEvent.click(screen.getByTestId('chat-send'));
};

describe('ChatWidget', () => {
  beforeEach(() => {
    sessionStorage.clear();
  });

  afterEach(() => {
    jest.useRealTimers();
    delete (global as any).fetch;
  });

  it('renders nothing when the assistant is disabled', async () => {
    const fetchMock = mockFetch({ [`GET ${API}/chat/status`]: () => response({ json: { enabled: false } }) });
    render(<ChatWidget userId="user-1" />);
    await waitFor(() => expect(fetchMock).toHaveBeenCalled());
    expect(screen.queryByTestId('chat-launcher')).not.toBeInTheDocument();
  });

  it('opens from the launcher and minimizes back to it', async () => {
    mockFetch({ [`GET ${API}/chat/status`]: enabledStatus });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    expect(screen.getByRole('heading', { name: 'CSS Assistant' })).toBeInTheDocument();
    expect(screen.getByText(/generated by AI/)).toBeInTheDocument();

    fireEvent.click(screen.getByLabelText('Minimize CSS Assistant'));
    expect(screen.queryByTestId('chat-window')).not.toBeInTheDocument();
    expect(screen.getByTestId('chat-launcher')).toHaveFocus();
  });

  it('closes on Escape', async () => {
    mockFetch({ [`GET ${API}/chat/status`]: enabledStatus });
    render(<ChatWidget userId="user-1" />);
    const win = await openWidget();
    fireEvent.keyDown(win, { key: 'Escape' });
    expect(screen.queryByTestId('chat-window')).not.toBeInTheDocument();
  });

  it('is hidden while the survey is shown and comes back after the survey has collapsed', async () => {
    mockFetch({ [`GET ${API}/chat/status`]: enabledStatus });
    const { rerender } = render(<ChatWidget userId="user-1" hidden={false} />);
    await screen.findByTestId('chat-launcher');

    jest.useFakeTimers();
    rerender(<ChatWidget userId="user-1" hidden />);
    expect(screen.getByTestId('chat-widget')).toHaveStyle({ display: 'none' });

    rerender(<ChatWidget userId="user-1" hidden={false} />);
    // Still hidden while the survey box animates away.
    expect(screen.getByTestId('chat-widget')).toHaveStyle({ display: 'none' });
    act(() => {
      jest.advanceTimersByTime(500);
    });
    expect(screen.getByTestId('chat-widget')).not.toHaveStyle({ display: 'none' });
  });

  it('streams an answer with its sources and the partial-grounding note', async () => {
    const fetchMock = mockFetch({
      [`GET ${API}/chat/status`]: enabledStatus,
      [`POST ${API}/chat`]: () => response({ body: streamBody(ANSWER_CHUNKS) }),
    });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    ask('How do I start?');

    expect(await screen.findByText('How do I start?')).toBeInTheDocument();
    await waitFor(() => expect(screen.getByRole('link', { name: 'Getting started' })).toBeInTheDocument());
    expect(screen.getByText('standard').tagName).toBe('STRONG');
    expect(screen.getByText('The documentation covers only part of this question.')).toBeInTheDocument();
    expect(screen.getByRole('link', { name: 'Getting started' })).toHaveAttribute('target', '_blank');

    const [, init] = fetchMock.mock.calls.find(([url, i]) => url === `${API}/chat` && i?.method === 'POST')!;
    expect(JSON.parse(init!.body as string)).toEqual({ prompt: 'How do I start?' });
    expect((init!.headers as Record<string, string>)['X-Tab-Id']).toMatch(/^[0-9a-f-]{36}$/);
    expect((init!.headers as Record<string, string>).Authorization).toBe('Bearer test-token');
  });

  it('shows the rate limit message from the proxy', async () => {
    mockFetch({
      [`GET ${API}/chat/status`]: enabledStatus,
      [`POST ${API}/chat`]: () =>
        response({ status: 429, json: { message: 'limit' }, headers: { 'Retry-After': '600' } }),
    });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    ask('Hello');
    expect(await screen.findByRole('alert')).toHaveTextContent('Please try again in about 10 minutes.');
  });

  it('shows an in-band stream error', async () => {
    mockFetch({
      [`GET ${API}/chat/status`]: enabledStatus,
      [`POST ${API}/chat`]: () => response({ body: streamBody([`data: ${JSON.stringify({ error: 'Boom.' })}\n\n`]) }),
    });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    ask('Hello');
    expect(await screen.findByRole('alert')).toHaveTextContent('Boom.');
  });

  it('starts a new chat with a new tab id', async () => {
    const fetchMock = mockFetch({
      [`GET ${API}/chat/status`]: enabledStatus,
      [`POST ${API}/chat`]: () => response({ body: streamBody(ANSWER_CHUNKS) }),
      [`DELETE ${API}/chat`]: () => response({ status: 204 }),
    });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    ask('How do I start?');
    await screen.findByRole('link', { name: 'Getting started' });
    const tabId = sessionStorage.getItem('css-assistant-tab-id');

    fireEvent.click(await menuOption('New chat'));
    await waitFor(() => expect(screen.queryByText('How do I start?')).not.toBeInTheDocument());
    await waitFor(() => expect(sessionStorage.getItem('css-assistant-tab-id')).not.toBe(tabId));
    const deleteCall = fetchMock.mock.calls.find(([url, i]) => url === `${API}/chat` && i?.method === 'DELETE')!;
    expect((deleteCall[1]!.headers as Record<string, string>)['X-Tab-Id']).toBe(tabId);
    expect((deleteCall[1]!.headers as Record<string, string>).Authorization).toBe('Bearer test-token');
  });

  it('deletes history after confirming, and keeps the dialog open to retry on failure', async () => {
    let attempts = 0;
    mockFetch({
      [`GET ${API}/chat/status`]: enabledStatus,
      [`POST ${API}/chat`]: () => response({ body: streamBody(ANSWER_CHUNKS) }),
      [`DELETE ${API}/chat/history`]: () =>
        ++attempts === 1
          ? response({ status: 502, json: { message: 'Some history could not be deleted. Please try again.' } })
          : response({ status: 204 }),
    });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    ask('How do I start?');
    await screen.findByRole('link', { name: 'Getting started' });

    fireEvent.click(await menuOption(/Delete history/));
    fireEvent.click(await screen.findByTestId('modal-confirm-btn-delete-chat-history'));
    expect(await screen.findByText('Some history could not be deleted. Please try again.')).toBeInTheDocument();
    expect(screen.getByText('How do I start?')).toBeInTheDocument();

    fireEvent.click(screen.getByTestId('modal-confirm-btn-delete-chat-history'));
    expect(await screen.findByText('Your chat history was deleted.')).toBeInTheDocument();
    expect(screen.queryByText('How do I start?')).not.toBeInTheDocument();
    expect(attempts).toBe(2);
  });

  it('disables deleting history while an answer is streaming', async () => {
    let finish: () => void = () => undefined;
    const pending = new Promise<void>((resolve) => (finish = resolve));
    const encoder = new TextEncoder();
    let sent = false;
    mockFetch({
      [`GET ${API}/chat/status`]: enabledStatus,
      [`POST ${API}/chat`]: () =>
        response({
          body: {
            getReader: () => ({
              read: async () => {
                if (!sent) {
                  sent = true;
                  return { done: false, value: encoder.encode(sse({ status: 'searching' })) };
                }
                await pending;
                return { done: true };
              },
              cancel: async () => undefined,
            }),
          } as any,
        }),
    });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    ask('Hello');

    expect(await screen.findByText('Searching the documentation…')).toBeInTheDocument();
    expect(await menuOption(/Delete history/)).toHaveAttribute('aria-disabled', 'true');

    await act(async () => finish());
    await waitFor(() =>
      expect(screen.getByRole('button', { name: /Delete history/ })).not.toHaveAttribute('aria-disabled'),
    );
  });

  it('restores the conversation after a page refresh, for the same user only', async () => {
    mockFetch({
      [`GET ${API}/chat/status`]: enabledStatus,
      [`POST ${API}/chat`]: () => response({ body: streamBody(ANSWER_CHUNKS) }),
    });
    const { unmount } = render(<ChatWidget userId="user-1" />);
    await openWidget();
    ask('How do I start?');
    await screen.findByRole('link', { name: 'Getting started' });
    unmount();

    // A refresh: the widget mounts again in the same tab.
    const { unmount: unmountAgain } = render(<ChatWidget userId="user-1" />);
    await openWidget();
    expect(screen.getByText('How do I start?')).toBeInTheDocument();
    expect(screen.getByText('standard').tagName).toBe('STRONG');
    expect(screen.getByRole('link', { name: 'Getting started' })).toBeInTheDocument();
    expect(screen.getByText('The documentation covers only part of this question.')).toBeInTheDocument();
    unmountAgain();

    // Another user signing in on the same tab doesn't see it.
    render(<ChatWidget userId="user-2" />);
    await openWidget();
    expect(screen.queryByText('How do I start?')).not.toBeInTheDocument();
    expect(screen.getByText(/I'm the CSS Assistant/)).toBeInTheDocument();
  });

  it('does not restore a conversation after starting a new chat', async () => {
    mockFetch({
      [`GET ${API}/chat/status`]: enabledStatus,
      [`POST ${API}/chat`]: () => response({ body: streamBody(ANSWER_CHUNKS) }),
      [`DELETE ${API}/chat`]: () => response({ status: 204 }),
    });
    const { unmount } = render(<ChatWidget userId="user-1" />);
    await openWidget();
    ask('How do I start?');
    await screen.findByRole('link', { name: 'Getting started' });
    fireEvent.click(await menuOption('New chat'));
    await waitFor(() => expect(screen.queryByText('How do I start?')).not.toBeInTheDocument());
    unmount();

    render(<ChatWidget userId="user-1" />);
    await openWidget();
    expect(screen.queryByText('How do I start?')).not.toBeInTheDocument();
  });

  it('offers New chat and Delete history from the header menu, and Escape closes only the menu', async () => {
    mockFetch({ [`GET ${API}/chat/status`]: enabledStatus });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    expect(screen.queryByRole('button', { name: 'New chat' })).not.toBeInTheDocument();

    // Nothing to clear yet; deleting stored history is still possible.
    expect(await menuOption('New chat')).toHaveAttribute('aria-disabled', 'true');
    expect(await menuOption(/Delete history/)).not.toHaveAttribute('aria-disabled');
    expect(screen.getByTestId('chat-menu')).toHaveAttribute('aria-expanded', 'true');

    fireEvent.keyDown(await menuOption('New chat'), { key: 'Escape' });
    await waitFor(() => expect(screen.getByTestId('chat-menu')).toHaveAttribute('aria-expanded', 'false'));
    expect(screen.getByTestId('chat-window')).toBeInTheDocument();
  });

  it('limits the question length', async () => {
    mockFetch({ [`GET ${API}/chat/status`]: () => response({ json: { enabled: true, maxPromptLength: 10 } }) });
    render(<ChatWidget userId="user-1" />);
    await openWidget();
    fireEvent.change(screen.getByTestId('chat-input'), { target: { value: 'a'.repeat(25) } });
    expect(screen.getByTestId('chat-input')).toHaveValue('a'.repeat(10));
    expect(screen.getByText('10/10')).toBeInTheDocument();
  });
});
